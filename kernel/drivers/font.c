static const uint8_t *find_glyph(char ch) {
    if (ch >= 'a' && ch <= 'z') {
        ch = (char)(ch - 32);
    }
    for (size_t i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); i++) {
        if (GLYPHS[i].ch == ch) {
            return GLYPHS[i].rows;
        }
    }
    return NULL; /* space and anything unrecognized: blank cell */
}

static void draw_glyph_bitmap(uint8_t *buf, uint32_t buf_w, uint32_t buf_h,
                               uint32_t x0, uint32_t y0, char ch,
                               uint32_t fg, uint32_t bg, uint32_t scale) {
    const uint8_t *rows = find_glyph(ch);

    for (uint32_t gy = 0; gy < GLYPH_H; gy++) {
        uint8_t rowbits = rows ? rows[gy] : 0;
        for (uint32_t gx = 0; gx < GLYPH_W; gx++) {
            int bit = (rowbits >> (GLYPH_W - 1 - gx)) & 1;
            fb_buf_fill_rect(buf, buf_w, buf_h, x0 + gx * scale, y0 + gy * scale,
                              scale, scale, bit ? fg : bg);
        }
    }
}

void font_draw_text_buf(uint8_t *buf, uint32_t buf_w, uint32_t buf_h,
                         uint32_t x, uint32_t y, const char *text,
                         uint32_t fg, uint32_t bg, uint32_t scale) {
    uint32_t cursor = x;
    if (g_ttf_ready) {
        uint32_t px_size = TTF_BASE_PX * scale;
        uint32_t adv = ttf_advance_width(&g_ttf, px_size);
        for (const char *p = text; *p; p++) {
            ttf_draw_glyph(&g_ttf, buf, buf_w, buf_h, cursor, y, *p, fg, bg, px_size);
            cursor += adv;
        }
        return;
    }
    for (const char *p = text; *p; p++) {
        draw_glyph_bitmap(buf, buf_w, buf_h, cursor, y, *p, fg, bg, scale);
        cursor += (GLYPH_W + 1) * scale;
    }
}

uint32_t font_glyph_width(uint32_t scale) {
    if (g_ttf_ready) {
        return ttf_advance_width(&g_ttf, TTF_BASE_PX * scale);
    }
    return GLYPH_W * scale;
}

uint32_t font_glyph_height(uint32_t scale) {
    if (g_ttf_ready) {
        return ttf_line_height(&g_ttf, TTF_BASE_PX * scale);
    }
    return GLYPH_H * scale;
}
